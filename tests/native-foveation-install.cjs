const fs=require('fs'),path=require('path'),os=require('os'),assert=require('node:assert/strict'),vm=require('vm');
const {createRequire}=require('module');
const file=path.resolve('src/core/native-foveation-install.js'),native=createRequire(file);
const temp=fs.mkdtempSync(path.join(os.tmpdir(),'native-foveation-test-'));
const payload=path.join(temp,'payload'),game=path.join(temp,'game');
fs.mkdirSync(path.join(payload,'vr-foveated'),{recursive:true});fs.mkdirSync(game);
const added=[],core={copyTracked:async(m,g,src,dst)=>{fs.copyFileSync(src,dst);added.push(path.basename(dst));},writeTracked:async(m,g,dst,text)=>{fs.writeFileSync(dst,text);added.push(path.basename(dst));},saveActiveManifest:async()=>{}};
